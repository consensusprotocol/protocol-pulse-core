#!/usr/bin/env python3
"""Yield per saved universe against the backtest's blind oracle (orchestrator 03:00; law L-n): the oracle's
moments-first line-ups judged to pass (/home/ultron/heimdall_probe/pp_redteam/oracle/<day>/moments/JUDGE_L*.json,
read-only) beside this session's miner + packager (tests/moments/proof/<run>/moments.json,
tests/package/proof/<run>/package.json). A universe where the oracle has a line-up that passes and this pipeline has no
package is a DEFECT to fix before DONE. Note the rules differ: the oracle judged caption-line timing without the
02:30 laws (one clip per channel L-u, context integrity L-s, layout DEC-12d); this pipeline applies them all.
Writes docs/audits/parallel/pp-selectid_YIELD.md."""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
ORACLE = "/home/ultron/heimdall_probe/pp_redteam/oracle"
OUT = os.path.join(REPO, "docs", "audits", "parallel", "pp-selectid_YIELD.md")
RUNS = ("fresh_20261106_213852", "fresh_20261107_065702", "fresh_20261107_080503", "fresh_20261110_093150",
        "fresh_20261111_190259", "fresh_20261111_192645", "fresh_20261111_213954", "fresh_20261112_001448",
        "fresh_20261112_013452", "fresh_20261112_050611")


def oracle_counts(run):
    """(moments-first line-ups the oracle judged to pass, story-first ones), or None when the oracle has no directory
    for this universe (never read as zero: audit p2 C17)."""
    day = run.replace("fresh_", "")
    if not os.path.isdir(os.path.join(ORACLE, day)):
        return None
    d = os.path.join(ORACLE, day, "moments")
    passed = 0
    for f in glob.glob(os.path.join(d, "JUDGE_L*.json")):
        if (json.load(open(f)).get("verdict") or "").upper() == "LEGAL":
            passed += 1
    story = 0
    for f in glob.glob(os.path.join(ORACLE, day, "JUDGE_L*.json")):
        if (json.load(open(f)).get("verdict") or "").upper() == "LEGAL":
            story += 1
    return passed, story


def main():
    rows = ["| universe | oracle: moments-first line-ups that pass / story-first | moments mined / usable | package | "
            "title | gates | defect? |", "|---|---|---|---|---|---|---|"]
    defects = 0
    for run in RUNS:
        oc = oracle_counts(run)
        mp, sp = oc if oc else (None, None)
        mf = os.path.join(REPO, "tests", "moments", "proof", run, "moments.json")
        pf = os.path.join(HERE, "proof", run, "package.json")
        m = json.load(open(mf)) if os.path.exists(mf) else None
        p = json.load(open(pf)) if os.path.exists(pf) else None
        mined = f"{len(m['moments'])} / {sum(1 for x in m['moments'] if x['on_screen_ok'] and not x['excluded'])}" \
            if m else "not mined"
        pk = (p or {}).get("package")
        pin_f = os.path.join(HERE, "proof", run, "MOMENTS_PIN.json")
        if not pk and os.path.exists(pin_f):                 # a sealed pin: every gate exactly PASS (package_pin refuses
            pin = json.load(open(pin_f))                     # anything else)
            mpk = pin.get("moments_package") or {}
            if mpk.get("gates") and all(g.get("status") == "PASS" for g in mpk["gates"].values()):
                pk = {"type": f"{mpk.get('type')}, pinned {pin.get('story_id')}", "segments": pin["segments"],
                      "runtime_s_estimate": mpk.get("runtime_s_estimate"), "title": mpk.get("title"),
                      "gates": mpk["gates"]}
        if pk:
            pkg, title = f"YES ({pk['type']}, {len(pk['segments'])} segments, ~{pk['runtime_s_estimate']} s)", pk["title"]
            gates = ", ".join(f"{k} {v['status']}" for k, v in (pk.get("gates") or {}).items()) or "NO GATE INVENTORY"
        else:
            pkg = "no" if p else "not run"
            title = "-"
            gates = (p or {}).get("why_none") or "; ".join(
                f"angle {t.get('angle')}: " + (t.get("why") or ", ".join(sorted({v["rule"] for a in t.get("attempts", [])
                                                                                  for v in a.get("violations", [])})))
                for t in (p or {}).get("tried", []))[:200] or "-"
        defect = "ORACLE MISSING" if oc is None else ("DEFECT (L-n)" if mp and not pk else "")
        defects += defect == "DEFECT (L-n)"
        rows.append(f"| {run} | {'-' if oc is None else f'{mp} / {sp}'} | {mined} | {pkg} | {title.replace('|', '/')} | {gates.replace('|', '/')} | "
                    f"{defect} |")
    text = "# pp-selectid — phase-2 yield against the blind oracle (generated by tests/package/yield_table.py)\n\n" + \
        "\n".join(rows) + f"\n\nDefects (oracle has a passing line-up, this pipeline none): {defects}\n"
    open(OUT, "w").write(text)
    print(text)


if __name__ == "__main__":
    main()
