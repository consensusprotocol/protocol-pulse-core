    while hi - lo > 1:                                 # the longest accepted command line (argv bytes as tmux counts)
        mid = (lo + hi) // 2
        line = "true #" + "x" * (mid - 6)
        r2 = tmux_new("pipeline_leantest_len", line)
        subprocess.run(["tmux", "kill-session", "-t", "=pipeline_leantest_len"], capture_output=True)
