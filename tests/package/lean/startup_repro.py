def old_lean_ops():
    src = subprocess.run(["git", "-C", REPO, "show", f"{AT}:tests/package/lean/lean_ops.py"], capture_output=True,
                         text=True, check=True).stdout
    d = tempfile.mkdtemp(prefix="lean_ops_at_")
    path = os.path.join(d, "lean_ops.py")
    with open(path, "w") as f:
        f.write(src)
    sys.path[:0] = [os.path.join(REPO, "pipeline"), os.path.join(REPO, "tests", "package"), HERE]
    spec = importlib.util.spec_from_file_location("lean_ops_at", path)
    m = importlib.util.module_from_spec(spec)
    m.__file__ = os.path.join(HERE, "lean_ops.py")    # its REPO, HERE and paths as in the worktree
    spec.loader.exec_module(m)
    return m


def tmux_new(name, line):
    return subprocess.run(["tmux", "new-session", "-d", "-s", name, "-c", "/var/tmp", line], capture_output=True,
                          text=True, stdin=subprocess.DEVNULL)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-dir", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    if not a.run_dir.startswith(("/tmp/", "/var/tmp/")) or "pp_lean_run" in a.run_dir.split("/"):
        raise SystemExit(f"refused: {a.run_dir} must be a scratch folder under /tmp or /var/tmp")
    LO = old_lean_ops()
    lines = []
    say = lines.append
    live_p = LO.paths("/home/ultron/pp_lean_run")
    td = LO.tops()
    live = LO.tmux_cmd(live_p, "lockcheck", LO.env_instance(live_p, "lockcheck", "build172"), td)
    shown = "  RUN the experimental lockcheck: " + " ".join(shlex.quote(str(x)) for x in live)
    logged = open(LIVE_LOG).read().split("\n")[35]
    say(f"THE 11:08 ET COMMAND, regenerated by lean_ops.py at {AT}: identical to the run log's line 36 (its first "
        f"4000 characters, all the log kept): {shown[:4000] == logged}")
    say(f"  its size as tmux counts it (each argument + 1): {sum(len(x.encode()) + 1 for x in live)} bytes "
        f"({len(td)} top folders overlaid)")
    p = LO.paths(a.run_dir)
    os.makedirs(os.path.join(a.run_dir, "offline", "lock_requests"), exist_ok=True)
    env = LO.env_instance(p, "lockcheck", "build172")
    env.update({"PP_LOCK_PRECHECK_EXTRA": os.path.join(a.run_dir, "offline", "lock_requests"),
                "PP_GPU0_WANT_DIR": os.path.join(a.run_dir, "offline", "gpu0_want"),
                "PP_SPEND_LEDGER_DIR": os.path.join(a.run_dir, "pp_spend")})
    LO.SESSIONS = {"lockcheck": "pipeline_leantest_lockcheck", "scorer": "pipeline_leantest_scorer"}
    cmd = LO.tmux_cmd(p, "lockcheck", env, td)
    kf = f"{LO.LIVE_MAIN}/{LO.KEYFILE}"
    old_bind = f"mount --bind {shlex.quote(p['hide'] + '/' + LO.KEYFILE)} {shlex.quote(kf)}"
    assert cmd[-1].count(old_bind) == 1 and cmd[-1].count(" unshare --user --map-root-user --mount bash ") == 1
    cmd[-1] = cmd[-1].replace(old_bind, f"mount --bind /dev/null {shlex.quote(kf)}; mount --bind /dev/null "
                                        f"{LO.LIVE_MAIN}/config/api_keys.json")
    cmd[-1] = cmd[-1].replace(" unshare --user --map-root-user --mount bash ",
                              " unshare --user --map-root-user --mount --net bash ")
    size = sum(len(x.encode()) + 1 for x in cmd)
    say(f"THE SAME COMMAND for the scratch run {a.run_dir} (session {cmd[4]}; --net; the keys from /dev/null; empty "
        f"requests): {size} bytes; run with its stdout and stderr to {a.out}.stderr")
    before = subprocess.run(["tmux", "list-sessions", "-F", "#{session_name}"], capture_output=True, text=True).stdout
    with open(a.out + ".stderr", "w") as fo:
        r = subprocess.run(cmd, stdout=fo, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL, text=True)
    err = open(a.out + ".stderr").read()
    after = subprocess.run(["tmux", "list-sessions", "-F", "#{session_name}"], capture_output=True, text=True).stdout
    say(f"  FIRST FAILING COMMAND: tmux new-session (the tmux client itself), exit {r.returncode}")
    say(f"  ITS MESSAGE, verbatim: {err!r}")
    say(f"  a session {cmd[4]} created: {cmd[4] in after.split()}; the tmux sessions before and after the same: "
        f"{before == after}; a service log written: "
        f"{os.path.exists(os.path.join(p['logs'], 'lockcheck.log'))}; nothing in the namespace ran")
    say("TMUX'S LIMIT, with a harmless padded `true` (session pipeline_leantest_len):")
